def classify(name: str):
    for sub, kws in RULES:
        for kw in kws:
            if kw in name:
                return sub
    return None


def main():
    result, unmatched = {}, []
    for code, name in sorted(sz.items()):
        sub = MANUAL.get(code) or classify(name)
        if sub:
            result.setdefault(sub, []).append({"code": code, "name": name})
        else:
            unmatched.append((code, name))
    print(f"已归类: {sum(len(v) for v in result.values())} 只 / {len(result)} 个子类")
    print(f"未归类: {len(unmatched)} 只")
    for c, n in unmatched:
        print(f"  {c} {n}")
    json.dump(result, open(os.path.join(ROOT, "scripts", "sz_classified.json"),
                          "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    # 子类统计
    print("\n子类分布:")
    for sub in sorted(result, key=lambda k: -len(result[k])):
        print(f"  {sub}: {len(result[sub])}")


if __name__ == "__main__":
    main()
